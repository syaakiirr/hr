const { chromium, expect: base } = require('@playwright/test');
const expect = base.configure({timeout:30000});
(async () => {
 const browser = await chromium.launch({args:['--enable-unsafe-swiftshader']});
 const page = await browser.newPage({viewport:{width:1440,height:950}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5174/',{waitUntil:'domcontentloaded',timeout:60000});
 const globe=page.locator('.hero-orbit canvas');
 await expect(globe).toHaveAttribute('data-ready','true');
 await expect(page.locator('.landing-logo-sphere canvas')).toHaveCount(0);
 const before=await globe.evaluate(c=>c.toDataURL());
 await page.waitForTimeout(700);
 if(before===await globe.evaluate(c=>c.toDataURL())) throw Error('Auto rotation frozen');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForTimeout(150);
 const still=await globe.evaluate(c=>c.toDataURL());
 await page.waitForTimeout(250);
 if(still!==await globe.evaluate(c=>c.toDataURL())) throw Error('Reduced motion not respected');
 const box=await globe.boundingBox();
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2); await page.mouse.down(); await page.mouse.move(box.x+box.width/2+80,box.y+box.height/2+20,{steps:8}); await page.mouse.up();
 if(still===await globe.evaluate(c=>c.toDataURL())) throw Error('Drag frozen');
 await page.screenshot({path:'.playwright-mcp/globe-performance-desktop.png'});
 await page.locator('#technology').scrollIntoViewIfNeeded();
 await expect(page.locator('.landing-logo-sphere canvas')).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:5174/',{waitUntil:'domcontentloaded'});
 await expect(globe).toHaveAttribute('data-ready','true');
 await page.screenshot({path:'.playwright-mcp/globe-performance-mobile.png'});
 if(errors.length) throw Error(errors.join('\n'));
 console.log('PASS rotation, drag, reduced motion, deferred logo sphere, desktop/mobile; no page errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
